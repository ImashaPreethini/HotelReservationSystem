    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
  try {
        Connection con = DB_Connection.connect();
        String query = "UPDATE rooms SET room_type=?, price_per_night=?, status=?, amenities=? WHERE room_no=?";
        
        PreparedStatement pst = con.prepareStatement(query);
        pst.setString(1, cmbRoomType.getSelectedItem().toString());
        pst.setDouble(2, Double.parseDouble(txtPrice.getText()));
        pst.setString(3, cmbStatus.getSelectedItem().toString());
       pst.setString(4, cmbAmenities.getSelectedItem().toString());
        pst.setInt(5, Integer.parseInt(txtRoomNo.getText())); // WHERE room_no = ?
        
        int result = pst.executeUpdate();
        if(result > 0) {
            JOptionPane.showMessageDialog(this, "Room Updated Successfully!");
            loadRoomData(); // Table එක අලුත් දත්ත වලින් Refresh කිරීම
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Update Failed: " + e.getMessage());
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
  if (txtRoomNo.getText().trim().isEmpty() || txtPrice.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all required fields (Room No and Price)!");
        return;
    }

    try {
        Connection con = DB_Connection.connect();
        
        String query = "INSERT INTO rooms (room_no, room_type, price_per_night, status, amenities) VALUES (?, ?, ?, ?, ?)";
        
        PreparedStatement pst = con.prepareStatement(query);
        pst.setInt(1, Integer.parseInt(txtRoomNo.getText()));
        pst.setString(2, cmbRoomType.getSelectedItem().toString());
        pst.setDouble(3, Double.parseDouble(txtPrice.getText()));
        pst.setString(4, cmbStatus.getSelectedItem().toString());
        pst.setString(5, cmbAmenities.getSelectedItem().toString());
        
        int result = pst.executeUpdate();
        if (result > 0) {
            JOptionPane.showMessageDialog(this, "New Room Added Successfully!");
            loadRoomData(); 
        }
    } catch (java.sql.SQLIntegrityConstraintViolationException e) {
        
        JOptionPane.showMessageDialog(this, "This Room Number already exists!");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Insertion Failed: " + e.getMessage());
    }
    }//GEN-LAST:event_btnAddActionPerformed
