    public void loadRoomData() {
        DefaultTableModel model = (DefaultTableModel) tblRooms.getModel();
        model.setRowCount(0); 
        
        model.setColumnIdentifiers(new String[]{"Room No", "Room Type", "Price", "Status", "Amenities"});

        try {
            Connection con = DB_Connection.connect(); 
            String query = "SELECT * FROM rooms";
            Statement stmt = con.createStatement();
            ResultSet rs = stmt.executeQuery(query);

            while (rs.next()) {
                int roomNo = rs.getInt("room_no");
                String type = rs.getString("room_type");
                double price = rs.getDouble("price_per_night");
                String status = rs.getString("status");
                String amenities = rs.getString("amenities");

                model.addRow(new Object[]{roomNo, type, price, status, amenities});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading data: " + e.getMessage());
        }
    }
    
    

