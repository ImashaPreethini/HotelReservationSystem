    private void btnCancelBookingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelBookingActionPerformed
   
    String roomNo = txtRoomNo.getText().trim();
    
    if (roomNo.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a booked room from the table first!", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    int confirm = javax.swing.JOptionPane.showConfirmDialog(this, 
            "Are you sure you want to cancel the pending booking for Room " + roomNo + "?", 
            "Confirm Cancellation", 
            javax.swing.JOptionPane.YES_NO_OPTION);

    if (confirm != javax.swing.JOptionPane.YES_OPTION) {
        return; 
    }

    String updateRoomSql = "UPDATE rooms SET status = 'Available' WHERE room_no = ?";
    String deleteBookingSql = "DELETE FROM bookings WHERE room_no = ? AND DATE(check_in_date) >= CURDATE()"; 

    try (java.sql.Connection conn = DB_Connection.connect()) {
        conn.setAutoCommit(false); 

        try (java.sql.PreparedStatement pst1 = conn.prepareStatement(updateRoomSql);
             java.sql.PreparedStatement pst2 = conn.prepareStatement(deleteBookingSql)) {
            
            pst1.setString(1, roomNo);
            pst1.executeUpdate();

            pst2.setString(1, roomNo);
            pst2.executeUpdate();

            conn.commit(); 
            
            javax.swing.JOptionPane.showMessageDialog(this, "Room " + roomNo + " has been successfully released!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
         
            loadRoomData(); 
            clearFields();  
            
        } catch (Exception ex) {
            conn.rollback(); 
            throw ex;
        }
    } catch (Exception e) {
        e.printStackTrace();
        javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_btnCancelBookingActionPerformed


