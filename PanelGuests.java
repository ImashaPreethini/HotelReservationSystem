    private void searchCustomer(String nic) {
        DefaultTableModel model = (DefaultTableModel) tblGuests.getModel();
        model.setRowCount(0); 
        
        
        model.setColumnIdentifiers(new String[]{"Guest ID", "Full Name", "NIC/Passport", "Contact Number"});

        String sql = "SELECT * FROM guests WHERE nic_or_passport = ?";
        
        try (Connection conn = DB_Connection.connect();
             PreparedStatement pst = conn.prepareStatement(sql)) {
            
            pst.setString(1, nic);
            ResultSet rs = pst.executeQuery();

            if (rs.next()) {
               int rawId = rs.getInt("guest_id");
               String formattedGuestId = String.format("G%03d", rawId);
                model.addRow(new Object[]{
                    formattedGuestId,
                  rs.getString("full_name"),
                    rs.getString("nic_or_passport"),
                    rs.getString("contact_number")
                });
                
                
                txtName.setText(rs.getString("full_name"));
                txtContact.setText(rs.getString("contact_number"));
                
                tblGuests.getParent().getParent().setVisible(true);
                this.revalidate();
                this.repaint();
                
            } else {
                JOptionPane.showMessageDialog(this, "Customer not found for this NIC!", "Not Found", JOptionPane.INFORMATION_MESSAGE);
                 tblGuests.getParent().getParent().setVisible(false);
            }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
            
           
        }
    }

