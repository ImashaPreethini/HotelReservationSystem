    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
                                                
        if (txtName.getText().isEmpty() || txtNIC.getText().isEmpty() || txtContact.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String sql = "INSERT INTO guests (full_name, nic_or_passport, contact_number) VALUES (?, ?, ?)";
        try (Connection conn = DB_Connection.connect();
             PreparedStatement pst = conn.prepareStatement(sql)) {

            pst.setString(1, txtName.getText());
            pst.setString(2, txtNIC.getText());
            pst.setString(3, txtContact.getText());
            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Customer Registered Successfully!");
            
            String currentNIC = txtNIC.getText();
            
            searchCustomer(currentNIC); 

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    
    }//GEN-LAST:event_btnRegisterActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
                                              
        if (txtNIC.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter the NIC to update!", "Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String sql = "UPDATE guests SET full_name = ?, contact_number = ? WHERE nic_or_passport = ?";
        try (Connection conn = DB_Connection.connect();
             PreparedStatement pst = conn.prepareStatement(sql)) {

            pst.setString(1, txtName.getText());
            pst.setString(2, txtContact.getText());
            pst.setString(3, txtNIC.getText());
            
            int rows = pst.executeUpdate();
            if (rows > 0) {
                JOptionPane.showMessageDialog(this, "Customer Updated Successfully!");
                searchCustomer(txtNIC.getText()); 
            } else {
                JOptionPane.showMessageDialog(this, "Customer NIC not found!");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
                                                
        if (txtNIC.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter the NIC to delete!", "Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this customer?", "Confirm", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            String sql = "DELETE FROM guests WHERE nic_or_passport = ?";
            try (Connection conn = DB_Connection.connect();
                 PreparedStatement pst = conn.prepareStatement(sql)) {

                pst.setString(1, txtNIC.getText());
                int rows = pst.executeUpdate();
                
                if (rows > 0) {
                    JOptionPane.showMessageDialog(this, "Customer Deleted Successfully!");
                    btnClearActionPerformed(null); 
                    DefaultTableModel model = (DefaultTableModel) tblGuests.getModel();
                    model.setRowCount(0); 
                } else {
                    JOptionPane.showMessageDialog(this, "Customer NIC not found!");
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Cannot delete! Customer might have bookings.");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

